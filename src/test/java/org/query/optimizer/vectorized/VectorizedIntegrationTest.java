    /**
     * Runs {@code sql} through both {@link ExecutionMode#VOLCANO} and
     * {@link ExecutionMode#VECTORIZED} and asserts identical result sets
     * (order-independent, column-name-prefixed string representation).
     */
    private void assertVectorizedMatchesVolcano(String sql) {
        // Parse + optimise — done twice so each engine gets an independent tree
        LogicalNode opt1 = optimise(sql);
        LogicalNode opt2 = optimise(sql);

        // Volcano path
        PhysicalNode        physicalPlan = physicalBuilder.build(opt1);
        ExecutionResult     volcanoResult = volcanoExec.execute(physicalPlan);

        // Vectorized path
        VectorizedOperator  vecPlan      = vecBuilder.build(opt2);
        ExecutionResult     vecResult    = vecExec.execute(vecPlan);

        assertEquals(
                volcanoResult.getResultCount(), vecResult.getResultCount(),
                "Row count mismatch [" + ExecutionMode.VOLCANO + " vs "
                + ExecutionMode.VECTORIZED + "] for: " + sql);

        assertEquals(
                serialise(volcanoResult.tuples()),
                serialise(vecResult.tuples()),
                "Result set mismatch for: " + sql);
    }

    private LogicalNode optimise(String sql) {
        return optimizer.optimize(logicalBuilder.build(parser.parse(sql)));
    }

    private static Set<String> serialise(List<Tuple> tuples) {
        return tuples.stream()
                .map(t -> t.stream()
                        .sorted(Comparator.comparing(a -> a.getKey().name()))
                        .map(a -> a.getKey().name() + "=" + a.getValue())
                        .collect(Collectors.joining("|")))
                .collect(Collectors.toSet());
    }

