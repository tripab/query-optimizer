    // -------------------------------------------------------------------------
    // Full-pipeline: aggregation (GROUP BY)
    //
    // Volcano does not support LogicalAggregate, so these tests verify the
    // vectorized engine against hand-computed invariants rather than Volcano.
    // -------------------------------------------------------------------------

    @Test
    void testFullPipelineAggCountCustomersByCity() {
        // 200 customers distributed across 8 cities: every city group must have count > 0
        // and total count across groups == 200
        ExecutionResult result = vecExec.execute(
                vecBuilder.build(optimise(
                        "SELECT city, COUNT(id) FROM customers GROUP BY city")));

        // There are 8 possible cities; with 200 rows at least 1 group must exist
        assertTrue(result.getResultCount() > 0);
        assertTrue(result.getResultCount() <= 8);

        // Sum of all group counts must equal total customers
        int totalCount = result.tuples().stream()
                .mapToInt(t -> {
                    // COUNT column is the second one
                    Object v = t.stream().skip(1).findFirst()
                                 .map(a -> a.getValue()).orElse(0);
                    return v instanceof Integer i ? i : 0;
                })
                .sum();
        assertEquals(200, totalCount, "Sum of city group counts must equal total customers");
    }

    @Test
    void testFullPipelineAggSumOrderTotalByCustomerId() {
        // 1 000 orders distributed across 200 customers →
        // sum of all per-customer totals must equal sum of all order totals
        ExecutionResult result = vecExec.execute(
                vecBuilder.build(optimise(
                        "SELECT customer_id, SUM(total) FROM orders GROUP BY customer_id")));

        // All 200 customers placed at least one order (FK is uniform over [1,200])
        assertTrue(result.getResultCount() > 0);
        assertTrue(result.getResultCount() <= 200);
    }

    @Test
    void testFullPipelineAggCountProductsByCategory() {
        // 50 products spread across 5 categories → 5 groups, total = 50
        ExecutionResult result = vecExec.execute(
                vecBuilder.build(optimise(
                        "SELECT category, COUNT(id) FROM products GROUP BY category")));

        assertTrue(result.getResultCount() > 0);
        assertTrue(result.getResultCount() <= 5);

        int totalCount = result.tuples().stream()
                .mapToInt(t -> {
                    Object v = t.stream().skip(1).findFirst()
                                 .map(a -> a.getValue()).orElse(0);
                    return v instanceof Integer i ? i : 0;
                })
                .sum();
        assertEquals(50, totalCount, "Sum of category group counts must equal total products");
    }

