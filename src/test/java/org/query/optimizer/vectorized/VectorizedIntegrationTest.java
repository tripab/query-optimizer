/**
 * Phase 4, task 4.4 — full pipeline end-to-end integration test.
 *
 * <p>Validates the complete query processing pipeline using tables generated by
 * {@link DataGenerator} (medium size: 200 customers, 50 products, 1 000 orders).
 * This is the first test class to exercise the entire path from a raw SQL string
 * all the way through to {@link VectorizedExecutor} results, using realistic data
 * volumes rather than hand-crafted micro-fixtures.
 *
 * <h2>Pipeline under test</h2>
 * <pre>
 *   SQL string
 *     → SQLParser           → AST
 *     → LogicalPlanBuilder  → LogicalNode tree
 *     → RuleEngine          → optimised LogicalNode tree
 *                                   │
 *               ┌───────────────────┴───────────────────┐
 *               │ ExecutionMode.VOLCANO                  │ ExecutionMode.VECTORIZED
 *               ▼                                        ▼
 *     PhysicalPlanBuilder                     VectorizedPlanBuilder
 *     PhysicalNode tree                       VectorizedOperator tree
 *     Executor.execute()                      VectorizedExecutor.execute()
 *               │                                        │
 *               └──────────── assertResultSetsEqual ─────┘
 * </pre>
 *
 * <h2>Query shapes covered</h2>
 * <ul>
 *   <li>Simple scan with projection</li>
 *   <li>Single-predicate filter (INTEGER, FLOAT, VARCHAR)</li>
 *   <li>Multi-predicate filter (AND) with projection</li>
 *   <li>Filter that eliminates all rows</li>
 *   <li>Two-table inner join with filter on each side</li>
 *   <li>Three-table join (customers → orders → products)</li>
 *   <li>Aggregation (GROUP BY with COUNT, SUM, AVG, MIN, MAX)</li>
 *   <li>Join + filter — mirrors queries in PhysicalExecutionDemo and
 *       RuleEngineAndOptimizationsDemo</li>
 * </ul>
 *
 * <h2>DataGenerator integration</h2>
 * <p>All three tables are populated by {@link DataGenerator#medium()} (200 customers,
 * 50 products, 1 000 orders) before any test runs, so the integration test exercises a
 * realistic dataset while remaining fast enough for a normal test suite pass.
 */
